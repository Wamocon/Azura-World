/**
 * Publish the journey's media, and only the journey's.        Owner: W-CINEMA
 *
 * The landing page showed **zero images and zero video** while 889 assets and
 * four real Azura videos sat encoded on disk. The cause was never rendering: it
 * was rights posture plus delivery. Every asset is `usage: "internal_only"` and
 * `delivery: "internal"`, meaning it lives in git-ignored `sources/media/…` and
 * may not be served from a public page. `apps/web/public/media` was empty.
 *
 * This script closes that gap in one auditable pass:
 *
 *   1. SELECT   per act, by objective rules, never by eye
 *   2. COPY     the AVIF + WebP rungs into `apps/web/public/media/`
 *   3. PROMOTE  the selected ids to `attributed_display` / `delivery: "public"`
 *               in `lib/media-manifest.ts`, with the reason written into the
 *               entry itself
 *   4. EMIT     `lib/journey-media.ts` — a SMALL generated module carrying only
 *               what the page renders
 *
 * ## Why step 4 exists, and why it is a budget decision rather than tidiness
 *
 * `lib/media-manifest.ts` is 25,204 lines. A landing page that imported it to
 * find eight photographs would pull the entire harvest into the client graph.
 * The page imports the generated module instead, which carries ~30 entries and
 * the four fields a `<picture>` needs. The manifest stays the authority; this is
 * a projection of it, regenerated by this script and never hand-edited.
 *
 * ## The rule that outranks the aesthetics
 *
 * Nine assets carry `subject: "unrelated"` — a portal that lists several
 * projects embeds media for all of them. **None may enter the journey.** The
 * filter is applied here, and `scripts/journey-media-guard.mjs` asserts it
 * against the emitted module so the two cannot drift.
 *
 * Run: `node scripts/publish-journey-media.mjs [--dry-run]`
 */

