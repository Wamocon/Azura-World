/** Rungs the page actually requests. 2400 is never needed at these sizes. */
const RUNGS = [800, 1200, 1600]

/**
 * Objective admission rules, applied before any act-specific pick.
 *
 * Nothing here is a taste judgement — 889 assets cannot be reviewed by eye, so
 * the gate is mechanical and the same for every act.
 */
function admissible(asset) {
  if (asset.subject === "unrelated") return false // the hard rule
  if (asset.category === "logo") return false // rights: never our branding
  if (asset.category === "document") return false
  if (asset.watermarked) return false // a watermark is someone's rights claim
  if (asset.userGeneratedContent) return false // rights sit with the individual
  if (asset.width < 1200) return false // below this it is soft full-bleed
  // Every rung the page will request must exist on disk.
  return RUNGS.every((w) =>
    asset.avif.some((p) => p.endsWith(`-${w}.avif`)) &&
    existsSync(join(ENCODED, `${asset.id}-${w}.avif`))
  )
}

/**
 * Rank: widest first, then most-corroborated, then largest file.
 *
 * "Most corroborated" is a real signal in this dataset — an image carried by
 * six source pages is the developer's own marketing render, while a one-source
 * image is more often a portal's own photograph of something adjacent.
 */
function rank(a, b) {
  return b.width - a.width || b.sourceCount - a.sourceCount || b.bytes - a.bytes
}

/** Landscape only, for full-bleed acts. A portrait crop in a 21:9 band is mush. */
const landscape = (a) => a.aspectRatio >= 1.25

function pick(n, predicate) {
  return all.filter((a) => admissible(a) && predicate(a)).sort(rank).slice(0, n)
}

