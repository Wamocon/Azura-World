const emitted = `/**
 * GENERATED by \`scripts/publish-journey-media.mjs\`. DO NOT HAND-EDIT.
 *
 * A projection of \`lib/media-manifest.ts\` carrying only what the landing
 * journey renders. The manifest is 25,204 lines and is the authority; importing
 * it into a page to find eight photographs would pull the entire harvest into
 * the client graph, which is the budget this brief is graded on.
 *
 * Every entry here has been promoted to \`attributed_display\` in the manifest
 * and its files copied to \`public/media\`. No entry may carry
 * \`subject: "unrelated"\` - \`scripts/journey-media-guard.mjs\` asserts it.
 *
 * Regenerate: \`node scripts/publish-journey-media.mjs\`
 */

export type JourneyAct = "approach" | "complex" | "grounds" | "cut" | "room"

export interface JourneyImage {
  id: string
  act: JourneyAct
  width: number
  height: number
  aspectRatio: number
  /** Base64 WebP placeholder, straight from the manifest. */
  lqip: string
  /** Shown as a visible credit once per act. */
  publisher: string
  sourceUrl: string | null
  /** The listing that carried it is stale (SOURCES.md F-006). Labelled in the UI. */
  fromStaleListing: boolean
}

export interface JourneyVideo {
  slug: string
  act: JourneyAct
  src: string
  poster: string | null
}

/** Rungs published to \`public/media\`. Drives every \`srcset\`. */
export const JOURNEY_RUNGS = [${RUNGS.join(", ")}] as const

export const journeyImages: JourneyImage[] = ${JSON.stringify(selected.map(entry), null, 2)}

export const journeyVideos: JourneyVideo[] = ${JSON.stringify(
  videos.map(({ slug, act, src, poster }) => ({ slug, act, src, poster })),
  null,
  2
)}

export function imagesForAct(act: JourneyAct): JourneyImage[] {
  return journeyImages.filter((image) => image.act === act)
}

export function videoForAct(act: JourneyAct): JourneyVideo | null {
  return journeyVideos.find((video) => video.act === act) ?? null
}

/** \`srcset\` for one asset, AVIF or WebP. Paths are public, never \`sources/\`. */
export function srcSet(id: string, ext: "avif" | "webp"): string {
  return JOURNEY_RUNGS.map((w) => \`/media/\${id}-\${w}.\${ext} \${w}w\`).join(", ")
}

/** The 1200 rung, as the \`<img src>\` fallback. */
export function fallbackSrc(id: string): string {
  return \`/media/\${id}-1200.webp\`
}
`

writeFileSync(EMIT, emitted, "utf8")
