// ---- promote in the manifest ----------------------------------------------

const REASON =
  "Promoted to attributed_display for the public landing journey on the repository owner's explicit instruction, recorded in MEDIA-LICENSE.md. Displayed with a visible publisher credit per act; never as our branding."

let promoted = 0
let out = source
for (const asset of selected) {
  // Anchor on the id so only that entry's fields are touched.
  const idAnchor = `id: "${asset.id}",`
  const at = out.indexOf(idAnchor)
  if (at === -1) continue
  const end = out.indexOf("\n  },", at)
  const entry = out.slice(at, end)
  const rewritten = entry
    .replace(/usage: "[^"]*",/, 'usage: "attributed_display",')
    .replace(/usageReason: "(?:[^"\\]|\\.)*",/, `usageReason: ${JSON.stringify(REASON)},`)
    .replace(/delivery: "[^"]*",/, 'delivery: "public",')
  if (rewritten !== entry) promoted += 1
  out = out.slice(0, at) + rewritten + out.slice(end)
}
writeFileSync(MANIFEST, out, "utf8")
console.log(`promoted ${promoted} manifest entries to attributed_display / public`)

