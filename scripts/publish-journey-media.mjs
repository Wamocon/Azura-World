const MANIFEST = join(APP, "lib", "media-manifest.ts")
const PUBLIC_MEDIA = join(APP, "public", "media")
const EMIT = join(APP, "lib", "journey-media.ts")
const DRY = process.argv.includes("--dry-run")

/**
 * The encoded derivatives are git-ignored and live in the ORIGINAL checkout, not
 * in this worktree — `sources/` is 2.6 GB and is deliberately not duplicated per
 * branch. Resolve there, and say so loudly if it is missing rather than emitting
 * a manifest full of paths to nothing.
 */
const ENCODED_ROOTS = [
  join(ROOT, "sources", "media", "encoded"),
  join(ROOT, "..", "Azura World", "sources", "media", "encoded"),
]
const VIDEO_ROOTS = [
  join(ROOT, "sources", "media", "videos"),
  join(ROOT, "..", "Azura World", "sources", "media", "videos"),
]

function resolveRoot(roots, label) {
  const found = roots.find((r) => existsSync(r))
  if (found === undefined) {
    console.error(`No ${label} directory found. Looked in:\n  ${roots.join("\n  ")}`)
    process.exit(2)
  }
  return found
}

const ENCODED = resolveRoot(ENCODED_ROOTS, "encoded media")
const VIDEOS = resolveRoot(VIDEO_ROOTS, "video")

