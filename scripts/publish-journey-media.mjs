// Idempotent: wipe what a previous run published before publishing again.
// The first run of this script promoted 26 entries; re-casting cut four of
// them, and without this the manifest keeps four assets marked
// `attributed_display` whose files no page references - a rights claim with no
// subject, which is the wrong direction to drift in.
if (existsSync(PUBLIC_MEDIA)) rmSync(PUBLIC_MEDIA, { recursive: true, force: true })
