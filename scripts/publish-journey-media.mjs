/**
 * Parse the asset array by scanning entries rather than importing the module.
 *
 * Importing would need the tsconfig alias loader and would pull 25k lines into
 * this process for four fields per row. The entries are machine-generated with a
 * stable shape, so a field scan is reliable — and every value it reads is
 * asserted non-empty below.
 */
function parseAssets(raw) {
  // The manifest is checked out with CRLF on Windows. Every anchor below is
  // written against `\n`; normalising once here is the difference between
  // parsing 833 entries and parsing zero, which is exactly what the first run
  // did.
  const text = raw.replace(/\r\n/g, "\n")
  const start = text.indexOf("export const mediaAssets")
  const end = text.indexOf("export const mediaVideos")
  const body = text.slice(start, end)
  const assets = []
  // Entries begin at a two-space `{` and end at the matching two-space `},`.
  // `split` consumes the delimiter, so each chunk begins at `    id: …` with no
  // leading newline — and every field regex below anchors on `\n    `. Putting
  // it back is what makes the FIRST field of each entry matchable; without it
  // `id` never matched and the parse returned zero rows while the split itself
  // was correct at 834.
  const chunks = body.split(/\n  \{\n/).slice(1).map((c) => `\n${c}`)
  for (const chunk of chunks) {
    const pick = (field) =>
      (chunk.match(new RegExp(`\\n    ${field}: "((?:[^"\\\\]|\\\\.)*)"`)) ?? [])[1] ?? null
    const pickNum = (field) =>
      Number((chunk.match(new RegExp(`\\n    ${field}: (-?[\\d.]+)`)) ?? [])[1] ?? 0)
    const id = pick("id")
    if (id === null) continue
    const avif = [...chunk.matchAll(/"(sources\/media\/encoded\/[^"]+\.avif)"/g)].map((m) => m[1])
    const webp = [...chunk.matchAll(/"(sources\/media\/encoded\/[^"]+\.webp)"/g)].map((m) => m[1])
    const publishers = [...chunk.matchAll(/publisher: "((?:[^"\\]|\\.)*)"/g)].map((m) => m[1])
    const urls = [...chunk.matchAll(/\{ url: "([^"]+)"/g)].map((m) => m[1])
    assets.push({
      id,
      category: pick("category"),
      subject: pick("subject"),
      width: pickNum("width"),
      height: pickNum("height"),
      aspectRatio: pickNum("aspectRatio"),
      bytes: pickNum("bytes"),
      lqip: pick("lqip"),
      usage: pick("usage"),
      watermarked: /\n    watermarked: true/.test(chunk),
      userGeneratedContent: /\n    userGeneratedContent: true/.test(chunk),
      fromStaleListing: /\n    fromStaleListing: true/.test(chunk),
      avif,
      webp,
      publishers: [...new Set(publishers)],
      sourceUrl: urls[0] ?? null,
      sourceCount: urls.length,
    })
  }
  return assets
}

const all = parseAssets(source)
console.log(`parsed ${all.length} assets from the manifest`)

